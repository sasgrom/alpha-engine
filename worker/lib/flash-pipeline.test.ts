import { describe, expect, it } from "vitest";
import { buildFactIndex, type SecFact } from "./flash-facts";
import { processRelease, sourceSha256, type ReleaseContext } from "./flash-pipeline";

const html = `
<p>GAAP to non-GAAP reconciliation</p><table><tr><td></td><td>September 26, 2026</td><td>September 27, 2025</td></tr><tr><td>Revenue</td><td>999</td><td>999</td><td>Operating income</td><td>999</td><td>999</td></tr></table>
<p>Consolidated Statements of Operations (In millions)</p><table>
<tr><td></td><td>Three Months Ended September 26, 2026</td><td>Three Months Ended September 27, 2025</td></tr>
<tr><td>Revenue</td><td>114477</td><td>102466</td></tr>
<tr><td>Net income</td><td>132175</td><td>112010</td></tr>
<tr><td>Nonstandard subtotal</td><td>12345</td><td>12345</td></tr>
<tr><td>Earnings per share</td><td></td><td></td></tr>
</table>
<p>Consolidated Balance Sheets (In millions)</p><table>
<tr><td></td><td>September 26, 2026</td><td>September 27, 2025</td></tr>
<tr><td>Total assets</td><td>404548</td><td>359241</td></tr>
<tr><td>Cash and cash equivalents</td><td>36305</td><td>35934</td></tr>
</table>
<p>Consolidated Statements of Cash Flows (In millions)</p><table>
<tr><td></td><td>Twelve Months Ended September 26, 2026</td><td>Twelve Months Ended September 27, 2025</td></tr>
<tr><td>Cash generated by operating activities</td><td>145097</td><td>111482</td></tr>
</table>`;

const fact = (concept: string, priorStart: string | null, currentStart: string | null, prior: number, current: number, unit = "USD", priorEnd = "2025-09-27", currentEnd = "2026-09-26"): SecFact[] => [
  { cik: 1, concept, unit, startDate: priorStart, endDate: priorEnd, val: prior, form: "10-Q", filed: "2025-10-30", accn: "old" },
  { cik: 1, concept, unit, startDate: currentStart, endDate: currentEnd, val: current, form: "10-Q", filed: "2026-11-03", accn: "periodic" },
];

describe("flash release pipeline", () => {
  it("links statements, printed values, grades and residuals with point-in-time evidence", () => {
    const release: ReleaseContext = { cik: 1, ticker: "AAA", accessionNo: "0000000001-26-000001", filingDate: "2026-10-01", acceptedEt: "2026-10-01T08:00:00", fiscalPeriodEnd: "2026-09-26", periodicAccession: "periodic", periodicForm: "10-Q" };
    const facts = [
      ...fact("Revenue", "2025-06-29", "2026-06-28", 102466000000, 114477000000),
      ...fact("NetIncomeLoss", "2025-06-29", "2026-06-28", 112010000000, 132175000000),
      ...fact("Assets", "2024-09-29", "2025-09-28", 359241000000, 404548000000),
      ...fact("CashAndCashEquivalentsAtCarryingValue", "2024-09-29", "2025-09-28", 35934000000, 36305000000),
      ...fact("NetCashProvidedByUsedInOperatingActivities", "2024-09-29", "2025-09-28", 111482000000, 145097000000),
    ];
    const result = processRelease(release, [{ file: "fixture.htm", sha256: sourceSha256(html), html }], buildFactIndex(facts));
    expect(result.statements.map((statement) => statement.statement)).toEqual(["income", "balance", "cashflow"]);
    expect(result.coverage).toMatchObject({ income: true, balance: true, cashflow: true, currentPeriodEnd: "2026-09-26", periodMatch: true, pitViolations: 0 });
    const revenue = result.values.find((row) => row.rowLabel === "Revenue" && row.current);
    expect(revenue).toMatchObject({ value: 114477000000, rawPrinted: "114477", howNamed: "answer_key", matchedConcepts: ["Revenue"] });
    expect(revenue?.evidence.every((match) => match.filed < release.filingDate)).toBe(true);
    expect(result.values.some((row) => !row.current)).toBe(true);
    expect(result.grades.length).toBeGreaterThan(0);
    expect(result.grades.every((grade) => grade.status === "match")).toBe(true);
    expect(result.grades.every((grade) => grade.valueId.endsWith("|0"))).toBe(true);
    const residual = result.residual.find((row) => row.rowLabel === "Nonstandard subtotal");
    expect(residual?.printedValues[0].value).toBe(12345000000);
    expect(result.residual.some((row) => row.rowKind === "heading")).toBe(true);
    expect(result.values.every((row) => row.evidence.every((match) => match.filed < release.filingDate))).toBe(true);
  });

  it("uses each row's own table units when a title fragment joins a data table", () => {
    const joinedHtml = `<p>Consolidated Statements of Income (In millions)</p><table><tr><td></td><td>Three Months Ended</td><td>Three Months Ended</td></tr><tr><td></td><td>July 31, 2026</td><td>July 31, 2025</td></tr><tr><td>Revenue</td><td>186100</td><td>175750</td></tr></table>
      <p>Consolidated Balance Sheets</p><table><tr><td>Walmart Inc.</td></tr></table>
      <p>(In millions)</p><table><tr><td></td><td>July 31, 2026</td><td>July 31, 2025</td></tr><tr><td>Total assets</td><td>293914</td><td>270837</td></tr><tr><td>Total liabilities</td><td>164177</td><td>162778</td></tr><tr><td>Total shareholders’ equity</td><td>6547</td><td>5454</td></tr></table>`;
    const release: ReleaseContext = { cik: 1, ticker: "AAA", accessionNo: "joined", filingDate: "2026-08-20", acceptedEt: null, fiscalPeriodEnd: "2026-07-31", periodicAccession: "periodic", periodicForm: "10-Q" };
    const facts = [
      ...fact("Revenue", "2025-05-01", "2026-05-01", 175750000000, 186100000000),
      ...fact("Assets", null, null, 270837000000, 293914000000, "USD", "2025-07-31", "2026-07-31"),
    ];
    const result = processRelease(release, [{ file: "joined.htm", sha256: sourceSha256(joinedHtml), html: joinedHtml }], buildFactIndex(facts));
    expect(result.values.find((row) => row.rowLabel === "Total assets" && row.current)?.value).toBe(293914000000);
  });

  it("selects the K01-compatible period over a later unrelated table", () => {
    const future = `<p>Consolidated Statements of Income (In millions)</p><table><tr><td></td><td>Three Months Ended September 25, 2027</td></tr><tr><td>Revenue</td><td>999</td></tr><tr><td>Operating income</td><td>99</td></tr></table><p>Consolidated Statements of Income (In millions)</p><table><tr><td></td><td>Three Months Ended September 26, 2026</td></tr><tr><td>Revenue</td><td>100</td></tr><tr><td>Operating income</td><td>10</td></tr></table>`;
    const release: ReleaseContext = { cik: 1, ticker: "AAA", accessionNo: "period-choice", filingDate: "2026-10-01", acceptedEt: null, fiscalPeriodEnd: "2026-09-26", periodicAccession: null, periodicForm: null };
    const result = processRelease(release, [{ file: "future.htm", sha256: sourceSha256(future), html: future }], buildFactIndex([]));
    expect(result.coverage.currentPeriodEnd).toBe("2026-09-26");
    expect(result.coverage.periodMatch).toBe(true);
  });
});
